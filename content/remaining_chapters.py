for chapter_number, chapter in CHAPTERS.items():
    for scene in chapter["scenes"]:
        normalized = []
        for beat in scene["beats"]:
            if isinstance(beat, str):
                spoken = CODE_NARRATION.get(chapter_number, {}).get(
                    beat, "看黑板上的代码示例，留意代码结构和它对应的结果。")
                normalized.append((spoken, beat))
            elif (isinstance(beat, tuple) and len(beat) == 2
                  and isinstance(beat[0], str) and beat[0].startswith("|")
                  and isinstance(beat[1], str)):
                # Extended scenes store a code sample first and its teaching
                # point second. Keep code on the board, but make the spoken
                # line explain the point instead of reading pipe delimiters.
                code, point = beat
                spoken = CODE_NARRATION.get(chapter_number, {}).get(code)
                if not spoken:
                    spoken = f"例如，这段代码展示了{point}。"
                normalized.append((spoken, code))
            else:
                normalized.append(beat)
        scene["beats"] = normalized

